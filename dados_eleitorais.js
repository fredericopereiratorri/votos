// Função para obter dados de um ano específico
function obterDadosAno(ano) {
    return dadosEleitorais.find(d => d["CANDIDATURA "].includes(ano.toString()));
}

// Função para normalizar nome do bairro (remove acentos, converte para maiúsculas)
function normalizarNome(nome) {
    return nome
        .toUpperCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '');
}

// Função para mapear nome do bairro para a chave do Excel
function mapearNomeBairro(nomeBairro) {
    const nomeNormalizado = normalizarNome(nomeBairro);

    // Mapeamento direto de nomes que podem ser diferentes
    const mapeamento = {
        'AGUAS COMPRIDAS': 'ÁGUAS COMPRIDAS',
        'CAIXA D\'AGUA': 'CAIXA D\'ÁGUA',
        'SAO BENEDITO': 'SÃO BENEDITO',
        'JD ATLANTICO': 'JD ATLANTICO',
        'JD BRASIL': 'JD BRASIL',
        'JD BRASIL 2': 'JD BRASIL 2',
        'JARDIM ATLANTICO': 'JD ATLANTICO',
        'JARDIM BRASIL': 'JD BRASIL',
        'JARDIM BRASIL 2': 'JD BRASIL 2'
    };

    // Tenta usar o mapeamento primeiro
    if (mapeamento[nomeNormalizado]) {
        return mapeamento[nomeNormalizado];
    }

    // Busca direta no primeiro objeto de dados (todas as chaves são as mesmas)
    const chavesDisponiveis = Object.keys(dadosEleitorais[0]);

    // Tenta encontrar correspondência exata
    for (let chave of chavesDisponiveis) {
        if (normalizarNome(chave) === nomeNormalizado) {
            return chave;
        }
    }

    // Se não encontrou, retorna o nome original
    return nomeBairro;
}

// Função para obter votos de um bairro em um ano específico
function obterVotosBairro(nomeBairro, ano) {
    const dadosAno = obterDadosAno(ano);
    if (!dadosAno) return 0;

    const chaveBairro = mapearNomeBairro(nomeBairro);
    const votos = dadosAno[chaveBairro];

    // Debug: log quando não encontrar correspondência
    if (votos === null || votos === undefined || isNaN(votos)) {
        console.log(`ℹ️ Bairro '${nomeBairro}' não tem dados na planilha para o ano ${ano}. Retornando 0 votos.`);
        return 0;
    }

    return votos;
}
